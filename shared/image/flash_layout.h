#pragma once

#include <stdint.h>

#define FLASH_BASE_ADDR 0x08000000U
#define FLASH_END_ADDR  0x08080000U
#define FLASH_SIZE      (FLASH_END_ADDR - FLASH_BASE_ADDR)

#define BOOTLOADER_START_ADDR 0x08000000U

#if defined(STM32F446xx)
#define BOOTLOADER_SIZE       0x00008000U
#define BOOT_STATE_START_ADDR 0x08008000U
#define BOOT_STATE_SIZE       0x00008000U
#define BOOT_STATE_COPY_STRIDE 0x00004000U
#define APP_SLOT_SIZE         0x00020000U
#define APP_SLOT_A_START_ADDR 0x08020000U
#define APP_SLOT_B_START_ADDR 0x08040000U
#else
#define BOOTLOADER_SIZE       0x00010000U
#define BOOT_STATE_START_ADDR 0x08010000U
#define BOOT_STATE_SIZE       0x00001000U
#define BOOT_STATE_COPY_STRIDE 0x00000100U
#define APP_SLOT_SIZE         0x00037000U
#define APP_SLOT_A_START_ADDR 0x08011000U
#define APP_SLOT_B_START_ADDR 0x08048000U
#endif

#define BOOTLOADER_END_ADDR   (BOOTLOADER_START_ADDR + BOOTLOADER_SIZE)

#define BOOT_STATE_END_ADDR   (BOOT_STATE_START_ADDR + BOOT_STATE_SIZE)

#define APP_SLOT_A_END_ADDR   (APP_SLOT_A_START_ADDR + APP_SLOT_SIZE)

#define APP_SLOT_B_END_ADDR   (APP_SLOT_B_START_ADDR + APP_SLOT_SIZE)

#define FLASH_RESERVED_START_ADDR APP_SLOT_B_END_ADDR
#define FLASH_RESERVED_SIZE       (FLASH_END_ADDR - FLASH_RESERVED_START_ADDR)
